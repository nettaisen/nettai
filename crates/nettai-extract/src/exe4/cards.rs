//! The e-Reader cards' chips (EXE4's chips 0x137 and 0x138: Duo and
//! PrixPowr). Their records are in every ROM, but point at RAM for what the
//! cards bring (the picture at 0x020008A0 and 0x02000E80, its palette at
//! 0x02000DE0 and 0x020013C0, the icon at 0x02000E00 and 0x020013E0): the
//! save's card data, which a new save fills with placeholders (0x08019708)
//! and scanning the cards replaces.
//!
//! - The icons are in every ROM all the same: the icon sheet's two slots
//!   after chip 0x136's, byte for byte the card data's.
//! - The pictures' tiles are in no ROM (the picture sheet's slots after
//!   chip 0x136's hold a fill): they are here, `DUO` and `PRIXPOWR`, so that
//!   the pack is whole from the ROMs alone. They are the card data's, the
//!   same in every save that holds it (the verification workspace's
//!   tools/exe4/gen_content.py holds these to the saves').
//! - The pictures' palettes are in no ROM either: the pack's pictures get
//!   a black one, and each chip's definition gives its own (`art_palette`),
//!   as EXE5's e-Reader chips' and EXE6's gift chips' do.

use super::rom::{Addresses, Rom};
use nettai_assets::{Picture, Tiles};

/// The last chip whose record points at its icon in the ROM: the cards'
/// chips' icons follow its in the icon sheet.
const BEFORE: u16 = 0x136;

/// A card's chip's picture (7x6 tiles of 4 bits a pixel, a tile a line), by
/// chip number.
fn tiles_of(id: u16) -> Option<&'static str> {
    match id {
        0x137 => Some(DUO),
        0x138 => Some(PRIXPOWR),
        _ => None,
    }
}

/// A card's chip's picture (its palette black: the definition's
/// `art_palette` colors it) and its icon from `rom`; none for another chip.
pub(super) fn media(rom: &Rom, a: &Addresses, id: u16, icon_bytes: usize) -> Option<(Picture, Tiles)> {
    let hex = tiles_of(id)?.as_bytes();
    let nibble = |c: u8| (c as char).to_digit(16).expect("the cards' pictures are hex") as u8;
    let bytes: Vec<u8> = hex.chunks(2).map(|p| nibble(p[0]) << 4 | nibble(p[1])).collect();
    let picture = Picture { tiles: Tiles::from_4bpp(&bytes), palette: Default::default() };
    let before = rom.u32(a.chip_table + 0x2C * BEFORE as u32 + 0x20);
    let icon = crate::decode::tiles(rom, before + (icon_bytes as u32) * (id - BEFORE) as u32, icon_bytes);
    Some((picture, icon))
}

