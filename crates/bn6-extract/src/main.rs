//! Extract game data from the original ROM into Rust source for bn6-battle.
//!
//! Usage: bn6-extract <exe6f_rom_f_e.srl> [out-dir]
//! (out-dir defaults to crates/bn6-battle/src/data)

use std::fmt::Write as _;
use std::path::PathBuf;

struct Rom(Vec<u8>);

impl Rom {
    fn u8(&self, a: u32) -> u8 {
        self.0[(a & 0x01FF_FFFF) as usize]
    }
    fn u16(&self, a: u32) -> u16 {
        u16::from_le_bytes([self.u8(a), self.u8(a + 1)])
    }
    fn bytes(&self, a: u32, n: usize) -> &[u8] {
        let o = (a & 0x01FF_FFFF) as usize;
        &self.0[o..o + n]
    }
}

