/// Battle actor lists: every list referenced by `BattleSettingsList1`
/// (192 16-byte settings records; bytes 12..16 point at the list). A list
/// is 4-byte entries up to one whose byte 0 has high nibble 0xF; the
/// spawn loop (`sub_8007368`) reads kind = b0 >> 4, side = b0 & 1,
/// x = b1 & 7, y = b1 >> 4, and kind-specific bytes b2, b3.
fn actor_lists(rom: &Rom) -> String {
    const SETTINGS: u32 = 0x080B_0D88;
    const COUNT: u32 = 192;
    let mut sources: Vec<u32> = (0..COUNT).map(|i| u32at(rom, SETTINGS + 16 * i + 12)).collect();
    sources.sort_unstable();
    sources.dedup();
    let mut out = String::from(HEADER);
    out.push_str("use crate::setup::{ActorEntry, ActorKind, ActorList};\n\n");
    writeln!(out, "/// Every actor list the battle settings table refers to, by ROM address.").unwrap();
    writeln!(out, "pub static ACTOR_LISTS: [ActorList; {}] = [", sources.len()).unwrap();
    for &source in &sources {
        let mut entries = Vec::new();
        let mut a = source;
        loop {
            let b = rom.bytes(a, 4);
            if b[0] >> 4 == 0xF {
                break;
            }
            // Each kind's spawn routine reads only some of the bytes;
            // the rest must be clear so the decoded entry says it all.
            let side = b[0] & 1;
            let unused = |mask0: u8, used2: bool| {
                assert!(
                    b[0] & mask0 == 0 && b[1] & 0x08 == 0 && (used2 || b[2] == 0) && b[3] == 0,
                    "actor entry {a:#010x} sets bytes its spawn routine ignores: {b:02x?}"
                )
            };
            let kind = match b[0] >> 4 {
                0 => {
                    unused(0x0E, false);
                    "ActorKind::Navi".to_string()
                }
                3 => {
                    unused(0x0F, false);
                    "ActorKind::Object6E".to_string()
                }
                8 => {
                    unused(0x0F, true);
                    format!("ActorKind::Rock {{ variant: {} }}", b[2])
                }
                9 => {
                    unused(0x0F, true);
                    format!("ActorKind::Object7D {{ variant: {} }}", b[2])
                }
                k => panic!("actor entry {a:#010x}: kind {k} has no ActorKind yet"),
            };
            entries.push(format!("ActorEntry {{ kind: {kind}, alliance: {side}, x: {}, y: {} }}", b[1] & 7, b[1] >> 4));
            a += 4;
        }
        writeln!(out, "    ActorList {{ source: {source:#010x}, entries: &[{}] }},", entries.join(", ")).unwrap();
    }
    out.push_str("];\n");
    out
}

/// The battle settings table (`BattleSettingsList1`, 192 16-byte records)
/// that a set's later rounds are drawn from (`battleSettings_802D2B2`).
/// Byte 1 (read outside the battle simulation) and byte 7 (no reader) are
/// not kept, as in `BattleSettings::netbattle_from_bytes`.
fn battle_settings(rom: &Rom) -> String {
    const SETTINGS: u32 = 0x080B_0D88;
    const COUNT: u32 = 192;
    let mut sources: Vec<u32> = (0..COUNT).map(|i| u32at(rom, SETTINGS + 16 * i + 12)).collect();
    sources.sort_unstable();
    sources.dedup();
    let mut out = String::from(HEADER);
    out.push_str("use super::ACTOR_LISTS;\nuse crate::setup::BattleSettings;\n\n");
    writeln!(out, "/// `BattleSettingsList1`, by index.").unwrap();
    writeln!(out, "pub static BATTLE_SETTINGS: [BattleSettings; {COUNT}] = [").unwrap();
    for i in 0..COUNT {
        let r = rom.bytes(SETTINGS + 16 * i, 16);
        let source = u32at(rom, SETTINGS + 16 * i + 12);
        let list = sources.binary_search(&source).unwrap();
        writeln!(
            out,
            "    BattleSettings {{ layout: {:#04x}, music: {:#04x}, mode: {}, background: {}, battle_number: {}, panel_pattern: {:#04x}, effects: {:#x}, actors: &ACTOR_LISTS[{list}] }}, // {i:#04x}",
            r[0],
            r[2],
            r[3],
            r[4],
            r[5],
            r[6],
            u32at(rom, SETTINGS + 16 * i + 8),
        )
        .unwrap();
    }
    out.push_str("];\n");
    out
}

/// Cross tables: the body overlays a navi wears (actor object #0x56:
/// sprites `byte_80C4320` and per-animation depth tables `off_80C42D4`)
/// and the extra height of a Cross navi's image as it merges with
/// MegaMan (`byte_80BC758`). The row types live in bn6-battle's
/// `data::cross`.
fn crosses(rom: &Rom) -> String {
    const OVERLAY_SPRITES: u32 = 0x080C_4320;
    const OVERLAY_DEPTHS: u32 = 0x080C_42D4;
    const OVERLAYS: u32 = 19;
    const MERGE_HEIGHTS: u32 = 0x080B_C758;
    const NAVIS: u32 = 13;
    let mut out = String::from(HEADER);
    out.push_str("use super::SpriteId;\nuse super::cross::BodyOverlay;\n\n");
    // The depth tables sit back to back and end where the pointer table
    // starts; an animation past a table's end reads the next one, so each
    // row runs to the end of the block.
    writeln!(out, "/// Body overlays by variant (Param1 of actor object #0x56).").unwrap();
    writeln!(out, "pub static BODY_OVERLAYS: [BodyOverlay; {OVERLAYS}] = [").unwrap();
    for i in 0..OVERLAYS {
        let s = rom.bytes(OVERLAY_SPRITES + 2 * i, 2);
        let depths = u32at(rom, OVERLAY_DEPTHS + 4 * i);
        assert!(depths < OVERLAY_DEPTHS, "overlay depth table {depths:#x} outside the block");
        let front: Vec<&str> = rom
            .bytes(depths, (OVERLAY_DEPTHS - depths) as usize)
            .iter()
            .map(|&b| match b {
                0 => "false",
                1 => "true",
                v => panic!("overlay depth byte {v:#x}"),
            })
            .collect();
        writeln!(
            out,
            "    BodyOverlay {{ sprite: SpriteId {{ category: {:#04x}, index: {:#04x} }}, in_front: &[{}] }}, // {i:#04x}",
            s[0],
            s[1],
            front.join(", ")
        )
        .unwrap();
    }
    out.push_str("];\n");
    let heights: Vec<String> = (0..NAVIS)
        .map(|i| {
            let v = u32at(rom, MERGE_HEIGHTS + 4 * i) as i32;
            assert_eq!(v & 0xFFFF, 0, "merge height {v:#x} is not whole pixels");
            (v >> 16).to_string()
        })
        .collect();
    writeln!(out, "/// Extra height (whole pixels) of a navi's image merging with MegaMan, by navi.").unwrap();
    writeln!(out, "pub static MERGE_HEIGHTS: [i16; {NAVIS}] = [{}];", heights.join(", ")).unwrap();
    out
}

/// Field-object tables: the rock variants (`byte_80CF934`, 8-byte rows
/// selected by the rock's first parameter) and the sprite of each kind of
/// obstacle when it is absorbed (`byte_80E98C0`).
fn obstacles(rom: &Rom) -> String {
    let mut out = String::from(HEADER);
    out.push_str("use super::{Element, RockKind, SpriteId};\n\n");
    const ROCKS: u32 = 0x080C_F934;
    let rows: Vec<String> = (0..4)
        .map(|i| {
            // Row bytes: standing animation, (unused), HP / 2, debris
            // palette, break sound (u16), name id (u16). The rock's init
            // (`sub_80CF974`) turns HP / 2 = 0 into 1 HP and makes
            // variants 3 and up aqua.
            let r = ROCKS + 8 * i;
            let hp = match rom.u8(r + 2) as u16 * 2 {
                0 => 1,
                hp => hp,
            };
            let element = if i >= 3 { "Aqua" } else { "Null" };
            format!(
                "RockKind {{ anim: {}, hp: {hp}, element: Element::{element}, debris_palette: {}, \
                 break_sound: {:#06x}, name_id: {:#06x} }}",
                rom.u8(r),
                rom.u8(r + 3),
                rom.u16(r + 4),
                rom.u16(r + 6)
            )
        })
        .collect();
    writeln!(out, "/// Rocks by variant, the rock's first parameter (`byte_80CF934`).").unwrap();
    writeln!(out, "pub static ROCKS: [RockKind; 4] = [\n    {},\n];", rows.join(",\n    ")).unwrap();
    const ABSORBED: u32 = 0x080E_98C0;
    let sprites: Vec<String> = (0..15)
        .map(|i| {
            let (category, index) = (rom.u8(ABSORBED + 2 * i), rom.u8(ABSORBED + 2 * i + 1));
            format!("SpriteId {{ category: {category:#04x}, index: {index:#04x} }}")
        })
        .collect();
    writeln!(out, "/// The sprite an absorbed obstacle flies with, by obstacle kind (`byte_80E98C0`).").unwrap();
    writeln!(out, "pub static ABSORBED_SPRITES: [SpriteId; 15] = [\n    {},\n];", sprites.join(",\n    ")).unwrap();
    out
}

/// Chip-attack tables: the secondary elements chip families add, the
/// attachment sprites (`byte_80B8BD4`, attachment object #5) and the
/// GunDelSol tables (`dword_80EDBC8`, `byte_80EDBB8`, and the sun beam's
/// sprites at `dword_80E5C28`).
fn attacks(rom: &Rom) -> String {
    let mut out = String::from(HEADER);
    out.push_str("use super::SpriteId;\n");
    out.push_str("use super::attacks::{AttachmentKind, SunBeamLook};\n");
    out.push_str("use super::player::SecondaryElements;\n\n");
    let list = |items: Vec<String>| items.join(", ");
    let sprite = |cat: u8, idx: u8| format!("SpriteId {{ category: {cat:#04x}, index: {idx:#04x} }}");

    let families: Vec<String> = (0..16).map(|i| format!("SecondaryElements({:#04x})", rom.u8(0x0801_29E4 + i))).collect();
    writeln!(out, "/// The secondary elements a chip family adds to its attacks (`byte_80129E4`).").unwrap();
    writeln!(out, "pub static FAMILY_ELEMENTS: [SecondaryElements; 16] = [{}];", list(families)).unwrap();

    // Five-byte rows: sprite category and index, palette, lift, attach
    // point (0 = not attached to a point).
    const ATTACHMENTS: u32 = 0x080B_8BD4;
    let rows: Vec<String> = (0..52)
        .map(|i| {
            let b = rom.bytes(ATTACHMENTS + 5 * i, 5);
            let point = if b[4] == 0 { "None".to_string() } else { format!("Some({})", b[4]) };
            format!(
                "AttachmentKind {{ sprite: {}, palette: {}, lift: {}, attach_point: {point} }}",
                sprite(b[0], b[1]),
                b[2],
                b[3] as i8
            )
        })
        .collect();
    writeln!(out, "/// Attachment kinds, the attachment's first parameter (`byte_80B8BD4`).").unwrap();
    writeln!(out, "pub static ATTACHMENTS: [AttachmentKind; 52] = [\n    {},\n];", rows.join(",\n    ")).unwrap();

    writeln!(out, "/// GunDelSol's firing ticks by level (`dword_80EDBC8`).").unwrap();
    writeln!(out, "pub static GUN_DEL_SOL_FIRING_TICKS: [u8; 4] = [{}];", list((0..4).map(|i| rom.u8(0x080E_DBC8 + i).to_string()).collect())).unwrap();
    let beams: Vec<String> = (0..2)
        .map(|sun| {
            let row: Vec<String> = (0..4)
                .map(|level| {
                    let a = 0x080E_DBB8 + 2 * (level + 4 * sun);
                    format!("SunBeamLook {{ sprite: {}, palette: {} }}", rom.u8(a), rom.u8(a + 1))
                })
                .collect();
            format!("[{}]", list(row))
        })
        .collect();
    writeln!(out, "/// GunDelSol's sun beam by [sun][level] (`byte_80EDBB8`).").unwrap();
    writeln!(out, "pub static GUN_DEL_SOL_BEAMS: [[SunBeamLook; 4]; 2] = [{}];", list(beams)).unwrap();
    let sprites: Vec<String> = (0..2).map(|i| sprite(rom.u8(0x080E_5C28 + 2 * i), rom.u8(0x080E_5C29 + 2 * i))).collect();
    writeln!(out, "/// The sun beam's sprites, by `SunBeamLook::sprite` (`dword_80E5C28`).").unwrap();
    writeln!(out, "pub static SUN_BEAM_SPRITES: [SpriteId; 2] = [{}];", list(sprites)).unwrap();
    out
}

/// Beast Out lock-on searches (`ho_8026554`, `jt_8026584`): for the lock-on
/// modes that look for a panel near the target (`sub_80265D0`), the panel
/// offsets tried, whether the middle row is preferred afterwards
/// (`sub_80265FE`), and the column shifts tried when nothing fits
/// (`byte_8026735`).
fn lockon(rom: &Rom) -> String {
    let mut out = String::from(HEADER);
    out.push_str("use super::PanelOffset;\n");
    out.push_str("use super::lockon::LockonSearch;\n\n");
    // A list of signed bytes (or byte pairs) up to 0x7F.
    let list = |mut a: u32, pairs: bool| {
        let mut v = Vec::new();
        while rom.u8(a) != 0x7F {
            if pairs {
                v.push(format!("PanelOffset {{ dx: {}, dy: {} }}", rom.u8(a) as i8, rom.u8(a + 1) as i8));
                a += 2;
            } else {
                v.push((rom.u8(a) as i8).to_string());
                a += 1;
            }
        }
        v
    };
    let shifts = list(u32at(rom, 0x0802_67E8), false);
    writeln!(out, "/// Column shifts toward the user tried when no panel next to the target fits (`byte_8026735`).").unwrap();
    writeln!(out, "pub static COLUMN_SHIFTS: [i8; {}] = [{}];", shifts.len(), shifts.join(", ")).unwrap();
    // (mode, literal-pool slot of its offset list, prefers the middle row)
    const MODES: [(u8, u32, bool); 12] = [
        (0x02, 0x0802_67FC, false),
        (0x03, 0x0802_6800, true),
        (0x04, 0x0802_6804, false),
        (0x05, 0x0802_6808, false),
        (0x06, 0x0802_680C, true),
        (0x07, 0x0802_6810, false),
        (0x08, 0x0802_6814, false),
        (0x09, 0x0802_6818, true),
        (0x0C, 0x0802_6824, false),
        (0x0D, 0x0802_6828, false),
        (0x0F, 0x0802_6830, false),
        (0x10, 0x0802_6834, true),
    ];
    writeln!(out, "/// The searching lock-on modes: panels next to the target, dx toward the user's front.").unwrap();
    writeln!(out, "pub static SEARCHES: [LockonSearch; {}] = [", MODES.len()).unwrap();
    for (mode, pool, middle) in MODES {
        let offsets = list(u32at(rom, pool), true);
        writeln!(
            out,
            "    LockonSearch {{ mode: {mode:#04x}, offsets: &[{}], prefers_middle_row: {middle} }},",
            offsets.join(", ")
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
    out
}

pub(crate) fn load_rom(path: &str) -> Rom {
    let rom = Rom(std::fs::read(path).expect("reading ROM"));
    assert_eq!(&rom.0[0xA0..0xB0], b"MEGAMAN6_FXXBR6E", "expected the US Falzar ROM (MEGAMAN6_FXXBR6E)");
    rom
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.first().map(String::as_str) == Some("assets") {
        assets::main(&args[1..]);
        return;
    }
    if args.first().map(String::as_str) == Some("content") {
        content::main(&args[1..]);
        return;
    }
    if args.first().map(String::as_str) == Some("graphics") {
        let (Some(rom), Some(out)) = (args.get(1), args.get(2)) else {
            eprintln!("usage: bn6-extract graphics <rom> <out-dir>");
            std::process::exit(2);
        };
        graphics::run(&load_rom(rom), std::path::Path::new(out));
        return;
    }
    let Some(rom) = args.first() else {
        eprintln!(
            "usage: bn6-extract <rom> [out-dir] | assets <rom> <sound-bank> | graphics <rom> <out-dir> | content <rom> <pack-dir>"
        );
        std::process::exit(2);
    };
    let rom = load_rom(rom);
    let out_dir = args
        .get(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../bn6-battle/src/data"));
    std::fs::write(out_dir.join("chips_generated.rs"), chips(&rom)).unwrap();
    std::fs::write(out_dir.join("banners_generated.rs"), banners(&rom)).unwrap();
    std::fs::write(out_dir.join("field_generated.rs"), field(&rom)).unwrap();
    std::fs::write(out_dir.join("collision_generated.rs"), collision(&rom)).unwrap();
    std::fs::write(out_dir.join("sprites_generated.rs"), sprites(&rom)).unwrap();
    std::fs::write(out_dir.join("effects_generated.rs"), effects(&rom)).unwrap();
    std::fs::write(out_dir.join("player_generated.rs"), player(&rom)).unwrap();
    std::fs::write(out_dir.join("actor_lists_generated.rs"), actor_lists(&rom)).unwrap();
    std::fs::write(out_dir.join("battle_settings_generated.rs"), battle_settings(&rom)).unwrap();
    std::fs::write(out_dir.join("cross_generated.rs"), crosses(&rom)).unwrap();
    std::fs::write(out_dir.join("obstacles_generated.rs"), obstacles(&rom)).unwrap();
    std::fs::write(out_dir.join("attacks_generated.rs"), attacks(&rom)).unwrap();
    std::fs::write(out_dir.join("lockon_generated.rs"), lockon(&rom)).unwrap();
    eprintln!("wrote {}", out_dir.display());
}
