"""Combine content declarations for luau-lsp, which loads each definitions file separately.

The extraction recipes' declarations (content/nettai/extract.d.luau and the .d.luau files under a pack's extract/)
are the recipes' alone, apart from the content's as the content check keeps them: they go to luau-extract.d.luau,
for editing a recipe."""

from pathlib import Path


def main():
    root = Path(__file__).resolve().parent.parent
    content = root / "content"
    engine = content / "nettai" / "core.d.luau"
    recipes = content / "nettai" / "extract.d.luau"
    others = sorted(path for path in content.rglob("*.d.luau") if path not in (engine, recipes))
    is_recipe = lambda path: "extract" in path.relative_to(content).parts[1:-1]
    write(root, "luau-globals.d.luau", [engine, *(p for p in others if not is_recipe(p))])
    write(root, "luau-extract.d.luau", [recipes, *(p for p in others if is_recipe(p))])


def write(root, name, sources):
    sections = [
        "-- Generated by .zed/generate-luau-definitions.py; edit the source declarations instead.\n"
        "-- Load together so references between the engine and pack types resolve.\n"
    ]
    for source in sources:
        sections.append(f"-- Source: {source.relative_to(root).as_posix()}\n{source.read_text(encoding='utf-8')}\n")
    destination = root / ".zed" / name
    destination.write_text("\n".join(sections), encoding="utf-8")
    print(f"Wrote {destination.relative_to(root)} from {len(sources)} declaration files.")


if __name__ == "__main__":
    main()
